BEGIN;

CREATE SCHEMA IF NOT EXISTS silver;

-- 1. Геолокация
CREATE TABLE IF NOT EXISTS silver.geolocation(
geolocation_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
geolocation_state CHAR(2) NOT NULL,
geolocation_city VARCHAR(64) NOT NULL,
geolocation_zip_code_prefix VARCHAR(9) NOT NULL,

CONSTRAINT uq_state_city_post_code_set
UNIQUE (geolocation_zip_code_prefix, geolocation_city, geolocation_state)
);

-- 2. Методы оплаты
CREATE TABLE IF NOT EXISTS silver.payment_types(
payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
payment_type VARCHAR(64) NOT NULL UNIQUE
);

-- 3. Имена категорий продуктов
CREATE TABLE IF NOT EXISTS silver.product_category_names(
product_category_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
product_category_name VARCHAR(128) NOT NULL UNIQUE,
product_category_name_english VARCHAR(128) NOT NULL UNIQUE
);

-- 4. Статусы заказов
CREATE TABLE IF NOT EXISTS silver.order_statuses (
status_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
status_name VARCHAR(32) NOT NULL UNIQUE
);

-- 5. Пользователи
CREATE TABLE IF NOT EXISTS silver.customers (
customer_id VARCHAR(32) PRIMARY KEY,
customer_unique_id VARCHAR(32) NOT NULL,
geolocation_id INT NOT NULL,

CONSTRAINT fk_geolocation_id
FOREIGN KEY (geolocation_id)
REFERENCES silver.geolocation(geolocation_id)
);

-- 6. Заказы
CREATE TABLE IF NOT EXISTS silver.orders(
order_id VARCHAR(32) NOT NULL PRIMARY KEY,
customer_id VARCHAR(32) NOT NULL,
status_id INT NOT NULL,
order_purchase_timestamp TIMESTAMP NOT NULL,
order_approved_at TIMESTAMP,
order_delivered_carrier_date TIMESTAMP,
order_delivered_customer_date TIMESTAMP,
order_estimated_delivery_date TIMESTAMP NOT NULL,

CONSTRAINT fk_status_id FOREIGN KEY (status_id)
	REFERENCES silver.order_statuses (status_id),
CONSTRAINT fk_customer_id FOREIGN KEY (customer_id)
	REFERENCES silver.customers (customer_id)
);

-- 7. Оплаты заказов
CREATE TABLE IF NOT EXISTS silver.order_payments(
order_id VARCHAR(32) NOT NULL,
payment_sequential SMALLINT NOT NULL,
payment_id INT NOT NULL,
payment_installments SMALLINT NOT NULL,
payment_value DECIMAL(10,2) NOT NULL,

PRIMARY KEY (order_id, payment_sequential),

CONSTRAINT fk_order_id FOREIGN KEY (order_id)
	REFERENCES silver.orders (order_id),
CONSTRAINT fk_payment_id FOREIGN KEY (payment_id)
	REFERENCES silver.payment_types (payment_id)
);

-- 8. Отзывы на заказы
CREATE TABLE IF NOT EXISTS silver.order_reviews(
review_id VARCHAR(32) NOT NULL,
order_id VARCHAR(32) NOT NULL,
review_score SMALLINT CHECK (review_score > 0 AND review_score <= 5) NOT NULL,
review_comment_title VARCHAR(64),
review_comment_message TEXT,
review_creation_date TIMESTAMP,
review_answer_timestamp TIMESTAMP NOT NULL,

PRIMARY KEY (review_id, order_id),

CONSTRAINT fk_order_id FOREIGN KEY (order_id)
	REFERENCES silver.orders (order_id)
);

-- 9. Продукты
CREATE TABLE IF NOT EXISTS silver.products(
product_id VARCHAR(32) PRIMARY KEY,
product_category_id INT NOT NULL, -- Ставлю NOT NULL, т.к. эти значения получат значение 'Без категории', думаю тут это приемлимо
product_name_lenght SMALLINT,
product_description_lenght INT,
product_photos_qty SMALLINT,
product_weight_g DECIMAL(10,2), -- до 99 тон вес допустимый, с головой хватит
product_length_cm DECIMAL(10,2),
product_height_cm DECIMAL(10,2),
product_width_cm DECIMAL(10,2),

CONSTRAINT fk_product_category_id FOREIGN KEY (product_category_id)
	REFERENCES silver.product_category_names (product_category_id)
);

-- 10. Продавцы
CREATE TABLE IF NOT EXISTS silver.sellers(
seller_id VARCHAR(32) PRIMARY KEY,
geolocation_id INT NOT NULL,

CONSTRAINT fk_geolocation_id FOREIGN KEY (geolocation_id)
	REFERENCES silver.geolocation (geolocation_id)
);

-- 11. Продукты в заказах
CREATE TABLE IF NOT EXISTS silver.order_items (
order_id VARCHAR(32) NOT NULL,
order_item_id SMALLINT NOT NULL,
product_id VARCHAR(32) NOT NULL,
seller_id VARCHAR(32) NOT NULL,
shipping_limit_date TIMESTAMP NOT NULL,
price DECIMAL(10,2) NOT NULL,
freight_value DECIMAL(10,2) NOT NULL,

PRIMARY KEY (order_id, order_item_id),

CONSTRAINT fk_order_id FOREIGN KEY (order_id)
	REFERENCES silver.orders (order_id),
CONSTRAINT fk_product_id FOREIGN KEY (product_id)
	REFERENCES silver.products (product_id),
CONSTRAINT fk_seller_id FOREIGN KEY (seller_id)
	REFERENCES silver.sellers (seller_id)
);

END;