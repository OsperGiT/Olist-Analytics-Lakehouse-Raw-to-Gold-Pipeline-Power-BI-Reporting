-- Глянем что хранится
SELECT * FROM raw.order_payments
ORDER BY order_id

-- В целом тут все довольно просто выглядит, проверим все столбцы на наличие null значений,
-- установим varchar 32 для order_id, посмотрим на максимально значение payment_sequential, payment_installments,
-- вероятно сделаем enum тип для payment_type

SELECT
	COUNT(*),
	COUNT(order_id) order_id_cnt,
	COUNT(DISTINCT order_id) d_order_id_cnt,
	MAX(LENGTH(order_id)) max_length_order_id,
	MIN(LENGTH(order_id)) min_length_order_id,
	COUNT(payment_sequential) payment_sequential_cnt,
	MAX(payment_sequential) max_payment_sequential,
	COUNT(payment_type) payment_type_cnt,
	COUNT(DISTINCT payment_type) d_payment_type_cnt,
	COUNT(payment_installments) payment_installments_cnt,
	MAX(payment_installments) max_payment_installments,
	COUNT(payment_value) payment_value_cnt,
	MAX(payment_value) max_payment_value
FROM raw.order_payments

-- Null значений нет, VARCHAR(32) ставим для заказа, payment_type вынесем в отдельную таблицу вместо enum, smallint для payment_installments и payment_sequential, payment value оставим как есть

-- Глянем типы оплат
SELECT
	payment_type
FROM raw.order_payments
GROUP BY payment_type

-- Надо рассмотреть почему order_id опять повторяются
WITH ranked_order_payments AS (	
	SELECT
		*,
		ROW_NUMBER() OVER(PARTITION BY order_id ORDER BY order_id) rn 
	FROM raw.order_payments
)
SELECT * FROM ranked_order_payments rop1
WHERE EXISTS (
	SELECT 1
	FROM ranked_order_payments rop2
	WHERE rop1.order_id = rop2.order_id
		AND rop2.rn >= 2
)
ORDER BY order_id, payment_sequential
-- Судя по всему айди заказа дублируется если у нас больше одного способа оплаты используется, получается идентификатором уникальности будет (order_id, payment_sequential)

SELECT COUNT(*), COUNT(DISTINCT (order_id, payment_sequential))
FROM raw.order_payments -- Да, таким образом получилось, что значения сошлись 103886 и 103886

-- Итоговые таблицы:
CREATE TABLE silver.payment_types(
payment_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
payment_type VARCHAR(64) NOT NULL UNIQUE
)

CREATE TABLE silver.order_payments(
order_id VARCHAR(32) NOT NULL,
payment_sequential SMALLINT NOT NULL,
payment_id INT NOT NULL,
payment_installments SMALLINT NOT NULL,
payment_value DECIMAL(10,2) NOT NULL,

PRIMARY KEY (order_id, payment_sequential),

CONSTRAINT fk_order_id FOREIGN KEY (order_id)
	REFERENCES silver.orders (order_id),
CONSTRAINT fk_payment_id FOREIGN KEY (payment_id)
	REFERENCES silver.payment_types (payment_id)
);